const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'../public/app.js'),'utf8');
let time=1000,attached=true;
const ctx=vm.createContext({performance:{now:()=>time},page:3,q:0,ready:true,paused:false,answers:[[],[]],render(){},go(n){ctx.page=n;},main:{contains:()=>attached,querySelector:()=>({focus(){}})}});
vm.runInContext(source.match(/\/\/ ANSWER INPUT START([\s\S]*?)\/\/ ANSWER INPUT END/)[1],ctx);
const button={dataset:{answer:'atas'},disabled:false},press=(detail=1)=>ctx.submitAnswer(button,{detail});
press();assert.equal(ctx.q,1);time+=50;press(2);assert.equal(ctx.q,1);
press(1);assert.equal(ctx.q,1,'Fast tap after DOM replacement counted twice');
time+=300;attached=false;press();assert.equal(ctx.q,1);attached=true;
ctx.paused=true;press();assert.equal(ctx.q,1);ctx.paused=false;
button.dataset.answer='invalid';press();assert.equal(ctx.q,1);button.dataset.answer='atas';
press();assert.equal(ctx.q,2);press(0);assert.equal(ctx.page,7);assert.equal(ctx.answers[0].length,3);
press(0);assert.equal(ctx.answers[0].length,3);
const state={mode:null,setup:[false,false],distanceEditing:false,calibration:null};ctx.formState=state;
vm.runInContext(source.match(/\/\/ PREPARATION STATUS START([\s\S]*?)\/\/ PREPARATION STATUS END/)[1],ctx);
assert(ctx.preparationMessage().includes('Pilih cara'));state.mode='solo';assert(ctx.preparationMessage().includes('Centang'));
state.setup=[true,true];state.distanceEditing=true;assert(ctx.preparationMessage().includes('catatan jarak'));
state.distanceEditing=false;state.calibration={status:'stale'};assert(ctx.preparationMessage().includes('ukuran layar'));
state.calibration.status='skipped';assert(ctx.preparationMessage().includes('siap'));
console.log('PASS: pointer duplicate lock, stale/invalid/paused input, keyboard activation, actionable preparation status');
