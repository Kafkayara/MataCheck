const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'../public/app.js'),'utf8');
const block=source.match(/\/\/ SCREENING STOP START([\s\S]*?)\/\/ SCREENING STOP END/);
assert(block,'Screening stop must discard the active session and require a new session');
const state={condition:'yes',consent:true,mode:'solo',setup:[true,true],practiced:true,switched:true,directions:[[0,1,2],[1]],completedAt:'old'};
const ctx=vm.createContext({formState:state,page:1,answers:[['atas','kanan','kiri'],['bawah']],ready:true,paused:true,interrupted:true,q:1,heldKeys:new Set(['p'])});
vm.runInContext(source.match(/function canEnter\(n\)\{.*?\}(?=\s*function go)/s)[0],ctx);
vm.runInContext(block[1],ctx);
ctx.stopScreening();
assert.equal(state.screeningStopped,true);assert.equal(ctx.answers.flat().length,0);assert.equal(state.directions.flat().length,0);
assert.equal(state.consent,false);assert.equal(state.practiced,false);assert.equal(state.switched,false);assert.equal(state.completedAt,null);
assert.equal(ctx.ready,false);assert.equal(ctx.paused,false);assert.equal(ctx.interrupted,false);assert.equal(ctx.heldKeys.size,0);
state.condition='no';state.consent=true;
for(const n of [2,3,4,5,6,7,8])assert.equal(ctx.canEnter(n),false,'Changing a screening answer must not resume the stopped session');
assert.equal(ctx.canEnter(1),true);assert.equal(ctx.canEnter(0),true);
ctx.stopScreening();assert.equal(ctx.answers.flat().length,0,'Repeated stop must be safe');
Object.assign(ctx,{root:{addEventListener(){}},go(n){ctx.page=n;}});
vm.runInContext(source.match(/\/\/ SESSION END START([\s\S]*?)\/\/ SESSION END END/)[1],ctx);
ctx.resetSession(1);assert.equal(state.screeningStopped,false);assert.equal(state.condition,null);assert.equal(state.consent,false);assert.equal(ctx.canEnter(2),false);
console.log('PASS: screening stop clears responses, locks all downstream routes, survives answer changes and resets only with a new session');
